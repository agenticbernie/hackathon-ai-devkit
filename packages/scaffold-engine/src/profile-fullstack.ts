function mapFeature(featureId: string, featureName: string): FeatureMapping {
  const comp = featureComponentName(featureId);
  const slug = featureId.replace(/_/g, '-');
  return {
    routes: [`src/app/api/${slug}/route.ts`],
    ui: [`src/components/${slug}.tsx`],
    services: [`src/core/${slug}/service.ts`],
    tests: [`tests/${slug}.test.ts`],
  };
}

